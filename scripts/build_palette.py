#!/usr/bin/env python3
"""Generate every distributable form of the Neurodesk colour palette.

One source of truth (PALETTE below) produces:

    palette/neurodesk-palette.json    machine-readable, for scripts and build tools
    palette/neurodesk-palette.css     CSS custom properties
    palette/neurodesk-palette.gpl     GIMP / Inkscape / Krita palette
    palette/neurodesk-palette.ase     Adobe Swatch Exchange (Illustrator, Photoshop,
                                      InDesign, Affinity, Figma)
    palette/neurodesk-palette.pptx    visual swatch card, opens in PowerPoint, Keynote,
                                      Google Slides and LibreOffice, with the Office
                                      theme colours set to match

Run:  python3 scripts/build_palette.py
"""

from __future__ import annotations

import json
import struct
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "palette"

# Authoritative values. Hex is canonical: these are the codes used in the website theme
# (_variables_project.scss, custom.css). RGB is derived, never entered by hand.
PALETTE = [
    ("Seafoam green",     "6aa329", "primary", "Primary actions"),
    ("Logo ink",          "101806", "primary", "The dark used in the logo artwork"),
    ("Black",             "0c0e0a", "secondary", "Regular text, menu bar"),
    ("Darkest green",     "161c10", "secondary", "Successful selection"),
    ("Muted olive green", "1e2a16", "secondary", "Accent background"),
    ("Dark olive green",  "4f7b38", "secondary", "Selected buttons, hyperlinks"),
    ("Light green",       "b7d886", "secondary", "Hover over a button"),
    ("Lighter green",     "d3e7b6", "secondary", ""),
    ("Verdant haze",      "e6f1d6", "secondary", "Unselected buttons"),
    ("Pale lime green",   "f0f7e7", "secondary", ""),
    ("White",             "ffffff", "secondary", ""),
]


def rgb(h: str) -> tuple[int, int, int]:
    return tuple(int(h[i : i + 2], 16) for i in (0, 2, 4))  # type: ignore[return-value]


def slug(name: str) -> str:
    return name.lower().replace(" ", "-")


def write_json() -> None:
    data = {
        "name": "Neurodesk",
        "source": "https://github.com/neurodesk/media",
        "licence": "CC-BY-4.0",
        "note": "Hex is canonical; RGB is derived from it.",
        "colours": [
            {
                "name": n,
                "slug": slug(n),
                "hex": f"#{h}",
                "rgb": list(rgb(h)),
                "group": g,
                "usage": u,
            }
            for n, h, g, u in PALETTE
        ],
    }
    (OUT / "neurodesk-palette.json").write_text(json.dumps(data, indent=2) + "\n")


def write_css() -> None:
    lines = [
        "/* Neurodesk colour palette",
        "   Generated by scripts/build_palette.py — do not edit by hand.",
        "   https://github.com/neurodesk/media  ·  CC-BY-4.0 */",
        "",
        ":root {",
    ]
    for n, h, _, u in PALETTE:
        comment = f"  /* {u} */" if u else ""
        lines.append(f"  --neurodesk-{slug(n)}: #{h};{comment}")
    lines += ["}", ""]
    (OUT / "neurodesk-palette.css").write_text("\n".join(lines))


def write_gpl() -> None:
    lines = ["GIMP Palette", "Name: Neurodesk", "Columns: 4", "#"]
    for n, h, _, _u in PALETTE:
        r, g, b = rgb(h)
        lines.append(f"{r:>3} {g:>3} {b:>3}\t{n}")
    (OUT / "neurodesk-palette.gpl").write_text("\n".join(lines) + "\n")


def write_ase() -> None:
    """Adobe Swatch Exchange. Big-endian throughout."""
    blocks = b""
    for n, h, _, _u in PALETTE:
        r, g, b = (c / 255.0 for c in rgb(h))
        name = n + "\x00"
        name_utf16 = name.encode("utf-16-be")
        body = (
            struct.pack(">H", len(name))
            + name_utf16
            + b"RGB "
            + struct.pack(">fff", r, g, b)
            + struct.pack(">H", 2)  # 2 = normal (not global or spot)
        )
        blocks += struct.pack(">HI", 0x0001, len(body)) + body
    data = b"ASEF" + struct.pack(">HH", 1, 0) + struct.pack(">I", len(PALETTE)) + blocks
    (OUT / "neurodesk-palette.ase").write_bytes(data)


def write_pptx() -> None:
    from pptx import Presentation
    from pptx.dml.color import RGBColor
    from pptx.util import Emu, Pt

    prs = Presentation()
    prs.slide_width, prs.slide_height = Emu(12192000), Emu(6858000)  # 16:9
    slide = prs.slides.add_slide(prs.slide_layouts[6])  # blank

    def textbox(l, t, w, h, text, size, bold=False, colour="0c0e0a", align_c=False):
        from pptx.enum.text import PP_ALIGN

        tb = slide.shapes.add_textbox(Emu(l), Emu(t), Emu(w), Emu(h))
        tf = tb.text_frame
        tf.word_wrap = True
        p = tf.paragraphs[0]
        if align_c:
            p.alignment = PP_ALIGN.CENTER
        r = p.add_run()
        r.text = text
        r.font.size = Pt(size)
        r.font.bold = bold
        r.font.color.rgb = RGBColor.from_string(colour.upper())
        return tb

    textbox(600000, 300000, 11000000, 500000, "Neurodesk colour palette", 32, True, "6aa329")
    textbox(
        600000, 800000, 11000000, 400000,
        "Hex is canonical. github.com/neurodesk/media  ·  CC BY 4.0",
        12, False, "4f7b38",
    )

    from pptx.enum.shapes import MSO_SHAPE

    cols, sw, sh = 6, 1700000, 1250000
    gap_x, gap_y = 1830000, 1900000
    x0, y0 = 600000, 1500000

    for i, (n, h, _g, _u) in enumerate(PALETTE):
        cx, cy = x0 + (i % cols) * gap_x, y0 + (i // cols) * gap_y
        sq = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, Emu(cx), Emu(cy), Emu(sw), Emu(sh))
        sq.fill.solid()
        sq.fill.fore_color.rgb = RGBColor.from_string(h.upper())
        sq.line.color.rgb = RGBColor.from_string("CCCCCC")
        sq.line.width = Pt(0.75)
        sq.shadow.inherit = False
        if sq.has_text_frame:
            sq.text_frame.text = ""
        textbox(cx, cy + sh + 60000, sw, 300000, n, 11, True, align_c=True)
        r, g, b = rgb(h)
        textbox(cx, cy + sh + 340000, sw, 300000, f"#{h}\n{r}, {g}, {b}", 9, False, "4f7b38", True)

    prs.save(OUT / "neurodesk-palette.pptx")


def main() -> None:
    OUT.mkdir(exist_ok=True)
    write_json()
    write_css()
    write_gpl()
    write_ase()
    write_pptx()
    for f in sorted(OUT.glob("neurodesk-palette.*")):
        print(f"  {f.name:<32}{f.stat().st_size / 1024:>8.1f} KB")


if __name__ == "__main__":
    main()
